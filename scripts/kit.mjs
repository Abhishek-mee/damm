/**
 * Agent kit installer.
 *
 * Copies the agents, skills, and rules into a target project without
 * overwriting anything the project already owns. The kit is local-only by
 * default: the paths are added to .git/info/exclude, so attaching DAMM never
 * changes the target's tracked files.
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './ownership.mjs';

export const KIT_VERSION = 2;
const KIT_MARKER = '.damm-kit.json';
const EXCLUDE_START = '# >>> DAMM agent kit (local only) >>>';
const EXCLUDE_END = '# <<< DAMM agent kit (local only) <<<';

function listFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...listFiles(absolute));
    else if (entry.isFile()) files.push(absolute);
  }
  return files;
}

function gitPath(target, name) {
  const result = spawnSync('git', ['rev-parse', '--git-path', name], {
    cwd: target,
    encoding: 'utf8',
    windowsHide: true,
  });
  if (result.status !== 0) return null;
  return path.resolve(target, result.stdout.trim());
}

function copyTree(source, destination, result) {
  for (const file of listFiles(source)) {
    const relative = path.relative(source, file).replace(/\\/g, '/');
    const target = path.join(destination, relative);
    if (fs.existsSync(target)) {
      const same = fs.readFileSync(file).equals(fs.readFileSync(target));
      if (same) result.unchanged += 1;
      else result.conflicts.push(path.relative(ROOT, target).replace(/\\/g, '/'));
      continue;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(file, target);
    result.copied.push(relative);
  }
}

function rulesDocument(project) {
  const source = fs.readFileSync(path.join(ROOT, 'AGENTS.md'), 'utf8');
  const workspace = path.relative(project, ROOT).replace(/\\/g, '/') || '.';
  const header = [
    '<!-- Generated by DAMM. Local-only; do not commit unless you want the kit in your history. -->',
    '',
    `> Attached to the DAMM workspace at \`${workspace}\`.`,
    '> Re-run `npm run attach -- <project>` from that workspace to update the kit.',
    '',
  ].join('\n');

  const adapted = source.replace(
    /Read these in order before changing anything:\n\n(?:.*\n)+?\n/,
    [
      'Read these in order before changing anything:',
      '',
      '1. `DAMM.md` (this file)',
      '2. Your own agent file in `.opencode/agents/`',
      '3. The workspace docs when you need the full model: `docs/WORKTREES.md` and `docs/AGENTS.md`',
      '',
    ].join('\n'),
  );

  return `${header}${adapted}`;
}

function writeExclude(target) {
  const excludePath = gitPath(target, 'info/exclude');
  if (!excludePath) return false;

  const block = [
    EXCLUDE_START,
    '.opencode/agents/',
    '.opencode/skills/',
    `.opencode/${KIT_MARKER}`,
    'DAMM.md',
    '.damm/',
    EXCLUDE_END,
  ].join('\n');

  const current = fs.existsSync(excludePath) ? fs.readFileSync(excludePath, 'utf8') : '';
  if (current.includes(EXCLUDE_START)) {
    const replaced = current.replace(
      new RegExp(`${EXCLUDE_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${EXCLUDE_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`),
      block,
    );
    if (replaced !== current) fs.writeFileSync(excludePath, replaced, 'utf8');
    return true;
  }

  fs.mkdirSync(path.dirname(excludePath), { recursive: true });
  const separator = current.endsWith('\n') || current === '' ? '' : '\n';
  fs.writeFileSync(excludePath, `${current}${separator}\n${block}\n`, 'utf8');
  return true;
}

/**
 * Install the kit into one checkout.
 *
 * Existing files are never overwritten. A file that exists with different
 * content is reported as a conflict so the human can decide.
 */
export function installKit(target, { exclude = true } = {}) {
  const result = { target, copied: [], unchanged: 0, conflicts: [], excluded: false };

  if (!fs.existsSync(target)) throw new Error(`Cannot install the kit: ${target} does not exist.`);

  for (const [source, destination] of [
    [path.join(ROOT, '.opencode', 'agents'), path.join(target, '.opencode', 'agents')],
    [path.join(ROOT, '.opencode', 'skills'), path.join(target, '.opencode', 'skills')],
  ]) {
    if (!fs.existsSync(source)) continue;
    copyTree(source, destination, result);
  }

  const rulesPath = path.join(target, 'DAMM.md');
  const rules = rulesDocument(target);
  if (!fs.existsSync(rulesPath)) {
    fs.writeFileSync(rulesPath, rules, 'utf8');
    result.copied.push('DAMM.md');
  } else if (fs.readFileSync(rulesPath, 'utf8') !== rules) {
    result.conflicts.push('DAMM.md');
  } else {
    result.unchanged += 1;
  }

  const markerPath = path.join(target, '.opencode', KIT_MARKER);
  fs.mkdirSync(path.dirname(markerPath), { recursive: true });
  fs.writeFileSync(
    markerPath,
    `${JSON.stringify({ version: KIT_VERSION, source: ROOT, installedAt: new Date().toISOString() }, null, 2)}\n`,
    'utf8',
  );

  if (exclude) result.excluded = writeExclude(target);
  return result;
}

export function kitState(target) {
  const markerPath = path.join(target, '.opencode', KIT_MARKER);
  if (!fs.existsSync(markerPath)) return null;
  try {
    return JSON.parse(fs.readFileSync(markerPath, 'utf8'));
  } catch {
    return { version: 0 };
  }
}

export function printKitResult(result, { quiet = false } = {}) {
  if (result.conflicts.length > 0) {
    console.log(`warn ${result.conflicts.length} file(s) already exist with different content and were left untouched:`);
    for (const conflict of result.conflicts.slice(0, 12)) console.log(`     ${conflict}`);
    if (result.conflicts.length > 12) console.log(`     ...and ${result.conflicts.length - 12} more`);
    console.log('     Rename or remove them, then re-run attach to install the DAMM version.');
  }

  if (!quiet) {
    console.log(
      `kit  ${result.copied.length} copied, ${result.unchanged} unchanged, ${result.conflicts.length} conflict(s)`,
    );
    if (result.excluded) console.log('     kit paths added to .git/info/exclude (local only)');
  }
}
